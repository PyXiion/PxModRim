from pxmodrim.core.organizer.defaults import StandardRule

# Proposed replacement for STANDARD_RULES. A folder such as "Gameplay/Combat"
# names a subfolder of the top-level "Gameplay" folder. Rules are ordered
# exact ids first, then prefixes by decreasing length, then the family rules
# that catch the rest of an author's catalogue; the first match wins. Mods
# whose purpose could not be established are matched by nothing.


def _exact(folder: str, *package_ids: str) -> tuple[StandardRule, ...]:
    return tuple(StandardRule(folder, "package_id", "equals", p) for p in package_ids)


def _prefixes(folder: str, *prefixes: str) -> tuple[StandardRule, ...]:
    return tuple(StandardRule(folder, "package_id", "prefix", p) for p in prefixes)


